import AppKit

/// The last texts copied on this Mac, newest first, for "panodaki son linki aç" and
/// "kopyaladığımı Ali'ye at". Kept in memory only and never written anywhere. What a password
/// manager marks as concealed or transient is never recorded.
@MainActor
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    private(set) var items: [String] = []
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let limit = 20
    /// Set on what Jarvis itself puts on the pasteboard (pasted dictation), which the user
    /// never copied. Other clipboard apps don't know it and keep such items as before.
    nonisolated static let ownType = NSPasteboard.PasteboardType("com.openwhisper.jarvis-write")
    /// nspasteboard.org markers for passwords and one-off content, and Jarvis's own writes.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        ownType.rawValue,
    ]

    /// Puts Jarvis's own text on the pasteboard, marked so the history skips it.
    nonisolated static func write(_ text: String) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, ownType], owner: nil)
        pasteboard.setData(Data(), forType: ownType)
        return pasteboard.setString(text, forType: .string)
    }

    /// The pasteboard has no change notification; a cheap counter check once a second.
    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty else { return }
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > Self.limit { items.removeLast() }
    }

    /// The newest copied text; the pasteboard itself when nothing was seen yet.
    var latest: String? {
        poll()
        return items.first
    }

    /// The newest link among the copied texts.
    var latestLink: URL? {
        poll()
        for item in items {
            if let url = Self.link(in: item) { return url }
        }
        return nil
    }

    nonisolated static func link(in text: String) -> URL? {
        guard let detector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue) else { return nil }
        let match = detector.firstMatch(in: text, range: NSRange(text.startIndex..., in: text))
        guard let url = match?.url, ["http", "https"].contains(url.scheme?.lowercased() ?? "") else { return nil }
        return url
    }

    func openLatestLink() async -> String {
        guard let url = latestLink else { return "Panoda link yok" }
        owLog("[Clipboard] Opening the latest copied link")
        return await BrowserController.open(url, done: "Panodaki link açılıyor")
    }
}
